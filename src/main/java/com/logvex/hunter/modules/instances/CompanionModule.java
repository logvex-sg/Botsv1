package com.logvex.hunter.modules.instances;

import com.logvex.hunter.HunterAddon;
import com.logvex.hunter.companion.MinecraftCompanionApi;
import com.logvex.hunter.core.HunterCore;
import com.logvex.hunter.core.companion.CompanionRouter;
import com.logvex.hunter.core.companion.CompanionServer;
import com.logvex.hunter.mc.HunterChat;
import com.logvex.hunter.modules.HunterModule;
import meteordevelopment.meteorclient.events.world.TickEvent;
import meteordevelopment.meteorclient.settings.BoolSetting;
import meteordevelopment.meteorclient.settings.IntSetting;
import meteordevelopment.meteorclient.settings.Setting;
import meteordevelopment.meteorclient.settings.SettingGroup;
import meteordevelopment.meteorclient.settings.StringSetting;
import meteordevelopment.orbit.EventHandler;

import java.security.SecureRandom;
import java.util.Base64;

/**
 * Runs the addon's companion HTTP endpoint so the Logvex Fleet Manager and the bundled web page
 * can read the hunter's state and send it commands.
 *
 * <p>Enabling this module is the on/off switch: while it is active the endpoint serves requests,
 * but only while the hunter itself is running. It binds to loopback unless remote access is
 * explicitly enabled and requires a bearer token. The routing logic lives in the Minecraft-free
 * core; this class only owns the socket lifecycle.
 */
public class CompanionModule extends HunterModule {
    private final SettingGroup sgGeneral = settings.getDefaultGroup();

    private final Setting<Integer> port = sgGeneral.add(new IntSetting.Builder()
        .name("port")
        .description("Port of the companion endpoint.")
        .defaultValue(8720).min(1).sliderRange(1024, 65535)
        .onChanged(value -> restart())
        .build());

    private final Setting<Boolean> allowRemote = sgGeneral.add(new BoolSetting.Builder()
        .name("allow-remote")
        .description("Accept connections from other machines. Leave off unless you need it.")
        .defaultValue(false)
        .onChanged(value -> restart())
        .build());

    private final Setting<String> token = sgGeneral.add(new StringSetting.Builder()
        .name("token")
        .description("Bearer token the Fleet Manager must send. A token is generated when empty.")
        .defaultValue("")
        .onChanged(value -> restart())
        .build());

    private CompanionServer server;
    private boolean applying;
    private boolean autoGeneratedToken;

    public CompanionModule() {
        super(HunterAddon.CATEGORY, "companion", "Serves the local HTTP endpoint for the Fleet Manager.");
    }

    @EventHandler
    private void onTick(TickEvent.Post event) {
        // The endpoint follows the master switch: no running hunter, no remote surface.
        boolean shouldRun = core().running();
        if (shouldRun && server == null) startServer();
        else if (!shouldRun && server != null) stopServer();
    }

    @Override
    public void onActivate() {
        core().statistics().recordModuleActivation(name);
        applySettings();
        core().config().setCompanionEnabled(true);
        core().markDirty();
        if (core().running()) startServer();
    }

    @Override
    public void onDeactivate() {
        stopServer();
        core().config().setCompanionEnabled(false);
        core().markDirty();
    }

    /** Copies the persisted configuration into the module settings without restarting twice. */
    private void applySettings() {
        applying = true;
        try {
            HunterCore core = core();
            port.set(core.config().companionPort());
            allowRemote.set(core.config().companionAllowRemote());
            token.set(core.config().companionToken());
        } finally {
            applying = false;
        }
    }

    private void restart() {
        if (applying) return;
        HunterCore core = core();
        core.config().setCompanionPort(port.get());
        core.config().setCompanionAllowRemote(allowRemote.get());
        core.config().setCompanionToken(token.get());
        core.markDirty();
        if (server != null) {
            stopServer();
            if (isActive() && core.running()) startServer();
        }
    }

    private void startServer() {
        if (server != null) return;
        HunterCore core = core();
        if (token.get().isBlank()) {
            String generated = generateToken();
            // Setting a value fires onChanged; guard so it does not re-enter restart() mid-start.
            applying = true;
            try {
                token.set(generated);
            } finally {
                applying = false;
            }
            core.config().setCompanionToken(generated);
            core.markDirty();
            autoGeneratedToken = true;
            HunterChat.warn("Companion token was empty; generated one: " + generated);
        }
        try {
            CompanionRouter router = new CompanionRouter(new MinecraftCompanionApi());
            server = new CompanionServer(port.get(), token.get(), allowRemote.get(), router);
            server.start();
            HunterChat.info("Companion endpoint listening on port " + server.port()
                + (allowRemote.get() ? " (remote access enabled)" : " (loopback only)"));
        } catch (Exception e) {
            server = null;
            HunterChat.error("Could not start the companion endpoint: " + e.getMessage());
        }
    }

    private void stopServer() {
        if (server == null) return;
        server.stop();
        server = null;
    }

    public boolean running() {
        return server != null;
    }

    public int boundPort() {
        return server == null ? 0 : server.port();
    }

    /** Regenerates the token, restarting the endpoint so the new token takes effect. */
    public String regenerateToken() {
        String generated = generateToken();
        applying = true;
        try {
            token.set(generated);
        } finally {
            applying = false;
        }
        core().config().setCompanionToken(generated);
        core().markDirty();
        autoGeneratedToken = false;
        if (server != null) {
            stopServer();
            if (core().running()) startServer();
        }
        return generated;
    }

    public String currentToken() {
        return token.get();
    }

    public boolean generatedToken() {
        return autoGeneratedToken;
    }

    private static String generateToken() {
        byte[] bytes = new byte[24];
        new SecureRandom().nextBytes(bytes);
        return Base64.getUrlEncoder().withoutPadding().encodeToString(bytes);
    }

    @Override
    public String getInfoString() {
        return server == null ? "off" : ":" + server.port();
    }
}
